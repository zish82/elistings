using Microsoft.EntityFrameworkCore;

namespace Server.Data;

/// <summary>
/// Columns/tables added after a PostgreSQL database was first created. EnsureCreated() only builds the schema on an
/// empty database, so later additions are applied here with idempotent SQL ("IF NOT EXISTS").
/// Not used once the project switches to EF migrations (dotnet ef migrations add InitialCreate).
/// Add new columns at the end; never remove lines (existing databases may still need them).
/// </summary>
public static class PostgresSchemaUpgrades
{
    private static readonly string[] Statements =
    {
        // Oct 2026: supplier categories on listings, supplier enable/disable, Safelincs price list.
        @"ALTER TABLE ""Listings"" ADD COLUMN IF NOT EXISTS ""SupplierCategory"" text NULL;",
        @"ALTER TABLE ""Listings"" ADD COLUMN IF NOT EXISTS ""QuantityZeroedAtUtc"" timestamp without time zone NULL;",
        @"ALTER TABLE ""SupplierProducts"" ADD COLUMN IF NOT EXISTS ""DeliveryCost"" numeric NULL;",
        @"CREATE TABLE IF NOT EXISTS ""SupplierPriceListItems"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_SupplierPriceListItems"" PRIMARY KEY,
            ""Supplier"" text NOT NULL,
            ""ProductCode"" text NOT NULL,
            ""Description"" text NULL,
            ""Category"" text NULL,
            ""Price"" numeric NOT NULL,
            ""DeliveryCost"" numeric NULL,
            ""UploadedAtUtc"" timestamp without time zone NOT NULL);",
        @"CREATE INDEX IF NOT EXISTS ""IX_SupplierPriceListItems_Supplier_ProductCode"" ON ""SupplierPriceListItems"" (""Supplier"", ""ProductCode"");",
    };

    public static void Apply(AppDbContext db)
    {
        foreach (var sql in Statements)
        {
            db.Database.ExecuteSqlRaw(sql);
        }
    }
}
