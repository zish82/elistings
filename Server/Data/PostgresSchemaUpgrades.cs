using Microsoft.EntityFrameworkCore;

namespace Server.Data;

/// <summary>
/// Columns/tables added after a PostgreSQL database was first created. EnsureCreated() only builds the schema on an
/// empty database, so later additions are applied here with idempotent SQL ("IF NOT EXISTS").
/// Not used once the project switches to EF migrations (dotnet ef migrations add InitialCreate).
/// Add new columns at the end; never remove lines (existing databases may still need them).
/// </summary>
public static class PostgresSchemaUpgrades
{
    private static readonly string[] Statements =
    {
        // Oct 2026: supplier categories on listings, supplier enable/disable, Safelincs price list.
        @"ALTER TABLE ""Listings"" ADD COLUMN IF NOT EXISTS ""SupplierCategory"" text NULL;",
        @"ALTER TABLE ""Listings"" ADD COLUMN IF NOT EXISTS ""QuantityZeroedAtUtc"" timestamp without time zone NULL;",
        @"ALTER TABLE ""SupplierProducts"" ADD COLUMN IF NOT EXISTS ""DeliveryCost"" numeric NULL;",
        @"CREATE TABLE IF NOT EXISTS ""SupplierPriceListItems"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_SupplierPriceListItems"" PRIMARY KEY,
            ""Supplier"" text NOT NULL,
            ""ProductCode"" text NOT NULL,
            ""Description"" text NULL,
            ""Category"" text NULL,
            ""Price"" numeric NOT NULL,
            ""DeliveryCost"" numeric NULL,
            ""UploadedAtUtc"" timestamp without time zone NOT NULL);",
        @"CREATE INDEX IF NOT EXISTS ""IX_SupplierPriceListItems_Supplier_ProductCode"" ON ""SupplierPriceListItems"" (""Supplier"", ""ProductCode"");",

        // Oct 2026: my categories, channel/supplier category mappings, supplier tags.
        @"ALTER TABLE ""Listings"" ADD COLUMN IF NOT EXISTS ""CatalogCategoryId"" integer NULL;",
        @"ALTER TABLE ""Listings"" ADD COLUMN IF NOT EXISTS ""CatalogCategoryIsManual"" boolean NOT NULL DEFAULT FALSE;",
        @"ALTER TABLE ""SupplierProducts"" ADD COLUMN IF NOT EXISTS ""CategoryPath"" text NULL;",
        @"ALTER TABLE ""SupplierProducts"" ADD COLUMN IF NOT EXISTS ""CatalogCategoryId"" integer NULL;",
        @"CREATE INDEX IF NOT EXISTS ""IX_SupplierProducts_CatalogCategoryId"" ON ""SupplierProducts"" (""CatalogCategoryId"");",
        @"CREATE TABLE IF NOT EXISTS ""CatalogCategories"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_CatalogCategories"" PRIMARY KEY,
            ""Name"" text NOT NULL,
            ""ParentId"" integer NULL,
            ""SortOrder"" integer NOT NULL,
            ""CreatedAtUtc"" timestamp without time zone NOT NULL);",
        @"CREATE INDEX IF NOT EXISTS ""IX_CatalogCategories_ParentId"" ON ""CatalogCategories"" (""ParentId"");",
        @"CREATE TABLE IF NOT EXISTS ""ChannelCategoryMappings"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_ChannelCategoryMappings"" PRIMARY KEY,
            ""CatalogCategoryId"" integer NOT NULL,
            ""Channel"" text NOT NULL,
            ""ExternalId"" text NOT NULL,
            ""ExternalName"" text NULL);",
        @"CREATE UNIQUE INDEX IF NOT EXISTS ""IX_ChannelCategoryMappings_CatalogCategoryId_Channel"" ON ""ChannelCategoryMappings"" (""CatalogCategoryId"", ""Channel"");",
        @"CREATE TABLE IF NOT EXISTS ""SupplierCategoryMappings"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_SupplierCategoryMappings"" PRIMARY KEY,
            ""Supplier"" text NOT NULL,
            ""SourceType"" text NOT NULL,
            ""SourceValue"" text NOT NULL,
            ""CatalogCategoryId"" integer NOT NULL);",
        @"CREATE UNIQUE INDEX IF NOT EXISTS ""IX_SupplierCategoryMappings_Supplier_SourceType_SourceValue"" ON ""SupplierCategoryMappings"" (""Supplier"", ""SourceType"", ""SourceValue"");",
        @"CREATE TABLE IF NOT EXISTS ""ProductTags"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_ProductTags"" PRIMARY KEY,
            ""Supplier"" text NOT NULL,
            ""Name"" text NOT NULL,
            ""NormalizedName"" text NOT NULL,
            ""Type"" text NOT NULL);",
        @"CREATE UNIQUE INDEX IF NOT EXISTS ""IX_ProductTags_Supplier_NormalizedName"" ON ""ProductTags"" (""Supplier"", ""NormalizedName"");",
        @"CREATE TABLE IF NOT EXISTS ""SupplierProductTags"" (
            ""Id"" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ""PK_SupplierProductTags"" PRIMARY KEY,
            ""SupplierProductId"" integer NOT NULL,
            ""ProductTagId"" integer NOT NULL);",
        @"CREATE UNIQUE INDEX IF NOT EXISTS ""IX_SupplierProductTags_SupplierProductId_ProductTagId"" ON ""SupplierProductTags"" (""SupplierProductId"", ""ProductTagId"");",
        @"CREATE INDEX IF NOT EXISTS ""IX_SupplierProductTags_ProductTagId"" ON ""SupplierProductTags"" (""ProductTagId"");",
    };

    public static void Apply(AppDbContext db)
    {
        foreach (var sql in Statements)
        {
            db.Database.ExecuteSqlRaw(sql);
        }
    }
}
